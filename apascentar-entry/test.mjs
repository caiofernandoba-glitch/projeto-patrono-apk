import {chromium} from "playwright";
import assert from "node:assert/strict";
import fs from "node:fs";
const browser=await chromium.launch({headless:true});
const context=await browser.newContext({viewport:{width:390,height:844},locale:"pt-BR"});
const page=await context.newPage();const errors=[];page.on("pageerror",e=>errors.push(e.message));
await page.goto("http://127.0.0.1:8765/assets/index.html");
const root=page.locator("#ap-entry-root");await root.waitFor({state:"visible"});
await assert.equal(await page.locator("#ap-entry-title").textContent(),"Bem-vindo ao Apascentar");
const go=page.locator(".ap-entry-submit");assert(await go.isDisabled());
assert.equal(await page.locator(".ap-entry-avatar").count(),12);
await page.locator("#ap-entry-name").fill("   ");await page.locator("[data-avatar=ester]").click();assert(await go.isDisabled());
await page.locator("#ap-entry-name").fill("  Caio  ");assert(await go.isEnabled());
assert.equal(await page.locator("[aria-checked=true]").count(),1);
await page.screenshot({path:"build-entry/entrada-mobile.png",fullPage:true});
await go.click();assert(await root.isHidden());
assert.deepEqual(await page.evaluate(()=>window.ApascentarProfile.read()),{version:1,name:"Caio",avatar:"ester"});
await page.evaluate(()=>localStorage.setItem("reader-test-preserved","existing reading note"));
await page.reload();assert(await root.isHidden());await page.locator("#ap-profile-open").click();assert(await root.isVisible());
await page.locator("#ap-entry-name").fill("Maria");await page.locator("[data-avatar=maria]").click();await go.click();
assert.equal(await page.evaluate(()=>localStorage.getItem("reader-test-preserved")),"existing reading note");
await page.reload();assert.equal(await page.evaluate(()=>window.ApascentarProfile.read().name),"Maria");
await page.locator("#ap-profile-open").click();await page.locator("#ap-entry-name").fill("Not saved");await page.locator(".ap-entry-cancel").click();assert.equal(await page.evaluate(()=>window.ApascentarProfile.read().name),"Maria");
await page.evaluate(()=>localStorage.setItem(window.ApascentarProfile.key,"invalid json"));await page.reload();assert(await root.isVisible());
const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);assert(!overflow);
const report={firstEntry:true,nameAndAvatarRequired:true,characters:12,persists:true,skipOnReopen:true,editProfile:true,cancelPreserves:true,existingDataPreserved:true,corruptStorageHandled:true,mobileNoOverflow:!overflow,pageErrors:errors};
fs.writeFileSync("build-entry/ui-test-report.json",JSON.stringify(report,null,2));
assert.equal(errors.length,0,"JavaScript errors");await browser.close();console.log(JSON.stringify(report));
